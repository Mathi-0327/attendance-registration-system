function dataTable(rows: Array<{ label: string; value: string }>): string {
  const trs = rows
    .map(
      (r) => `<tr>
      <td style="padding:10px 12px;font-size:13px;color:#64748b;font-weight:500;border-bottom:1px solid #f1f5f9;width:150px;">${r.label}</td>
      <td style="padding:10px 12px;font-size:14px;color:#0f172a;font-weight:600;border-bottom:1px solid #f1f5f9;">${r.value}</td>
    </tr>`
    )
    .join("");

  return `<table cellpadding="0" cellspacing="0" style="width:100%;margin:18px 0;background:#f8fafc;border-radius:8px;border:1px solid #e2e8f0;overflow:hidden;">
    ${trs}
  </table>`;
}

// ─────────────────────────────────────────────
// ATTENDANCE NOTIFICATION SERVICE CLASS
// ─────────────────────────────────────────────

export class AttendanceNotificationService {
  /**
   * Main entry point: dispatch attendance notifications to Student and Parent
   */
  async notifyAttendance(event: AttendanceNotificationEvent): Promise<{ studentNotified: boolean; parentNotified: boolean }> {
    let studentNotified = false;
    let parentNotified = false;

    try {
      const student = await studentRepository.findByStudentId(event.studentId);
      const parent = await studentRepository.getParentDetails(event.studentId);

      const timestamp = event.timestamp || new Date();
      const timeStr = timestamp.toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit", hour12: true });
      const dateStr = timestamp.toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric" });
      const sessionName = event.sessionName || "Regular Session";
      const studentName = event.studentName || student?.name || "Student";
      const department = event.department || student?.department || "Academic Department";

      // ─────────────────────────────────────────────────────────────
      // 1. NOTIFY STUDENT
      // ─────────────────────────────────────────────────────────────
      if (student?.email) {
        const studentSubject = this.getStudentSubject(event.status, studentName, sessionName, dateStr);
        const studentHtml = this.buildStudentHtml(event.status, studentName, event.studentId, department, sessionName, dateStr, timeStr, event.lateByMinutes);

        const emailResult = await emailService.sendEmail({
          to: student.email,
          subject: studentSubject,
          html: studentHtml,
          text: `Attendance Update: You were marked ${event.status.toUpperCase()} for "${sessionName}" on ${dateStr} at ${timeStr}.`,
        });

        await this.recordLog({
          studentId: event.studentId,
          recipientType: "student",
          recipientName: student.name,
          recipientContact: student.email,
          channel: "email",
          notificationType: event.status,
          sessionId: event.sessionId || null,
          subject: studentSubject,
          status: emailResult.success ? "sent" : "failed",
          errorMessage: emailResult.error || null,
          sentAt: emailResult.success ? new Date() : null,
        });

        studentNotified = emailResult.success;
      }

      if (student?.phone) {
        const studentSmsBody = `[AttendReg] Hi ${studentName}, your attendance for "${sessionName}" is recorded as ${event.status.toUpperCase()} at ${timeStr} on ${dateStr}.`;
        const studentSmsResult = await smsService.sendSms({
          to: student.phone,
          body: studentSmsBody,
        });

        await this.recordLog({
          studentId: event.studentId,
          recipientType: "student",
          recipientName: student.name,
          recipientContact: student.phone,
          channel: "sms",
          notificationType: event.status,
          sessionId: event.sessionId || null,
          subject: `SMS Alert: ${event.status.toUpperCase()}`,
          status: studentSmsResult.success ? "sent" : "failed",
          errorMessage: studentSmsResult.error || null,
          sentAt: studentSmsResult.success ? new Date() : null,
        });
      }

      // ─────────────────────────────────────────────────────────────
      // 2. NOTIFY PARENT / GUARDIAN (EMAIL + SMS)
      // ─────────────────────────────────────────────────────────────
      const parentEmail = parent?.email || parent?.fatherEmail || parent?.motherEmail || parent?.guardianEmail;
      const parentPhone = parent?.phone || parent?.fatherPhone || parent?.motherPhone || parent?.guardianPhone;
      const parentName = parent?.parentName || parent?.fatherName || parent?.motherName || parent?.guardianName || "Parent/Guardian";
      const relationship = parent?.relationship || "Guardian";

      // Check parent notification preference
      const isPreferenceEnabled =
        (event.status === "present" && (parent?.notifyOnPresent ?? true)) ||
        (event.status === "late" && (parent?.notifyOnLate ?? true)) ||
        (event.status === "absent" && (parent?.notifyOnAbsent ?? true));

      if (parentEmail && isPreferenceEnabled) {
        const parentSubject = this.getParentSubject(event.status, studentName, sessionName, dateStr);
        const parentHtml = this.buildParentHtml(
          event.status,
          parentName,
          relationship,
          studentName,
          event.studentId,
          department,
          sessionName,
          dateStr,
          timeStr,
          event.lateByMinutes
        );

        const emailResult = await emailService.sendEmail({
          to: parentEmail,
          subject: parentSubject,
          html: parentHtml,
          text: `Dear ${parentName}, attendance update for your ward ${studentName} (${event.studentId}): Marked ${event.status.toUpperCase()} for "${sessionName}" on ${dateStr} at ${timeStr}.`,
        });

        await this.recordLog({
          studentId: event.studentId,
          recipientType: "parent",
          recipientName: parentName,
          recipientContact: parentEmail,
          channel: "email",
          notificationType: event.status,
          sessionId: event.sessionId || null,
          subject: parentSubject,
          status: emailResult.success ? "sent" : "failed",
          errorMessage: emailResult.error || null,
          sentAt: emailResult.success ? new Date() : null,
        });

        parentNotified = emailResult.success;
      }

      // 3. Multi-Channel SMS Dispatch
      if (parentPhone && isPreferenceEnabled) {
        const smsBody = this.getSmsBody(event.status, studentName, event.studentId, sessionName, dateStr, timeStr, event.lateByMinutes);
        console.log(`[sms-provider] Dispatching SMS to parent (${parentPhone}) for ${studentName}: status ${event.status.toUpperCase()}`);
        
        const smsResult = await smsService.sendSms({
          to: parentPhone,
          body: smsBody,
        });

        await this.recordLog({
          studentId: event.studentId,
          recipientType: "parent",
          recipientName: parentName,
          recipientContact: parentPhone,
          channel: "sms",
          notificationType: event.status,
          sessionId: event.sessionId || null,
          subject: `SMS Alert: ${event.status.toUpperCase()}`,
          status: smsResult.success ? "sent" : "failed",
          errorMessage: smsResult.error || null,
          sentAt: smsResult.success ? new Date() : null,
        });
      }
    } catch (err: any) {
      console.error("[attendance-notification] Error dispatching attendance notification:", err.message);
    }

    return { studentNotified, parentNotified };
  }

  /**
   * Send a direct custom SMS to a phone number and log the audit trail
   */
  async sendDirectSms(options: {
    to: string;
    message: string;
    studentId?: string;
    recipientName?: string;
  }): Promise<{ success: boolean; messageId?: string; error?: string }> {
    const formattedTo = options.to.startsWith("+") ? options.to : `+91${options.to}`;
    const result = await smsService.sendSms({
      to: formattedTo,
      body: options.message,
    });

    await this.recordLog({
      studentId: options.studentId || "SYSTEM",
      recipientType: "parent",
      recipientName: options.recipientName || "Parent",
      recipientContact: formattedTo,
      channel: "sms",
      notificationType: "custom_sms",
      sessionId: null,
      subject: "Direct SMS Message",
      status: result.success ? "sent" : "failed",
      errorMessage: result.error || null,
      sentAt: result.success ? new Date() : null,
    });

    return result;
  }

  private getSmsBody(
    status: string,
    studentName: string,
    studentId: string,
    sessionName: string,
    date: string,
    time: string,
    lateByMinutes?: number
  ): string {
    switch (status) {
      case "present":
        return `[AttendReg] Dear Parent, ${studentName} (${studentId}) is marked PRESENT for ${sessionName} at ${time} on ${date}.`;
      case "late":
        return `[AttendReg] Dear Parent, ${studentName} (${studentId}) arrived LATE (${lateByMinutes || 10}m) for ${sessionName} at ${time} on ${date}.`;
      case "absent":
        return `[AttendReg] Dear Parent, ${studentName} (${studentId}) is marked ABSENT for ${sessionName} on ${date}. Contact college office if unexpected.`;
      default:
        return `[AttendReg] Attendance update for ${studentName} (${studentId}) in ${sessionName}: status ${status}.`;
    }
  }

  /**
   * Persist a notification attempt into SQLite notification_logs table
   */
  async recordLog(data: {
    studentId: string;
    recipientType: "student" | "parent";
    recipientName: string | null;
    recipientContact: string;
    channel: "email" | "sms" | "whatsapp" | "push";
    notificationType: string;
    sessionId: number | null;
    subject: string | null;
    status: "sent" | "failed" | "queued";
    errorMessage: string | null;
    sentAt: Date | null;
  }): Promise<void> {
    try {
      await db.insert(notificationLogs).values({
        studentId: data.studentId,
        recipientType: data.recipientType,
        recipientName: data.recipientName,
        recipientContact: data.recipientContact,
        channel: data.channel,
        notificationType: data.notificationType,
        sessionId: data.sessionId,
        subject: data.subject,
        status: data.status,
        errorMessage: data.errorMessage,
        sentAt: data.sentAt,
        createdAt: new Date(),
      });
    } catch (err: any) {
      console.warn("[notification-logs] Failed to write notification log:", err.message);
    }
  }

  /**
   * Retrieve notification logs with pagination for admin viewer
   */
  async getLogs(limit = 100): Promise<NotificationLogItem[]> {
    try {
      const logs = await db.select().from(notificationLogs).orderBy(desc(notificationLogs.createdAt)).limit(limit);
      return logs as NotificationLogItem[];
    } catch (err: any) {
      console.warn("[notification-logs] Error fetching logs:", err.message);
      return [];
    }
  }

  // ─────────────────────────────────────────────
  // SUBJECT & HTML GENERATORS
  // ─────────────────────────────────────────────

  private getStudentSubject(status: string, studentName: string, sessionName: string, date: string): string {
    switch (status) {
      case "present":
        return `✅ Attendance Confirmed: ${sessionName} — ${date}`;
      case "late":
        return `⏰ Late Arrival Recorded: ${sessionName} — ${date}`;
      case "absent":
        return `⚠️ Absence Alert: ${sessionName} — ${date}`;
      default:
        return `Attendance Update: ${sessionName}`;
    }
  }

  private getParentSubject(status: string, studentName: string, sessionName: string, date: string): string {
    switch (status) {
      case "present":
        return `✅ Attendance Update: ${studentName} is PRESENT in ${sessionName} (${date})`;
      case "late":
        return `⏰ Late Arrival Alert: ${studentName} was LATE for ${sessionName} (${date})`;
      case "absent":
        return `❌ Absence Alert: ${studentName} was marked ABSENT for ${sessionName} (${date})`;
      default:
        return `Attendance Update for ${studentName}`;
    }
  }

  private buildStudentHtml(
    status: string,
    studentName: string,
    studentId: string,
    department: string,
    sessionName: string,
    date: string,
    time: string,
    lateBy?: number
  ): string {
    let badge = { text: "PRESENT", color: "#16a34a" };
    let intro = `<p style="font-size:15px;line-height:1.6;margin:0 0 16px;">Hello <strong>${studentName}</strong>, your attendance has been successfully recorded for today's session.</p>`;

    if (status === "late") {
      badge = { text: `LATE (${lateBy || 10} MIN)`, color: "#d97706" };
      intro = `<p style="font-size:15px;line-height:1.6;margin:0 0 16px;">Hello <strong>${studentName}</strong>, your attendance was recorded as <strong>Late</strong> by ${lateBy || 10} minute(s).</p>`;
    } else if (status === "absent") {
      badge = { text: "ABSENT", color: "#dc2626" };
      intro = `<p style="font-size:15px;line-height:1.6;margin:0 0 16px;">Hello <strong>${studentName}</strong>, you were marked <strong>Absent</strong> for the following session. If you believe this is an error, please submit an attendance correction request through your student portal.</p>`;
    }

    const rows = [
      { label: "Student Name", value: studentName },
      { label: "Student ID", value: studentId },
      { label: "Department", value: department },
      { label: "Session", value: sessionName },
      { label: "Date", value: date },
      { label: "Recorded Time", value: time },
      { label: "Status", value: status.toUpperCase() },
    ];

    return emailShell(
      `Attendance Update — ${studentName}`,
      badge.text,
      badge.color,
      `
      <h2 style="margin:0 0 12px;font-size:20px;font-weight:700;color:#0f172a;">Attendance Update</h2>
      ${intro}
      ${dataTable(rows)}
      <p style="font-size:13px;color:#64748b;margin:16px 0 0;">
        You can view your complete attendance history and statistics anytime by logging into the Student Portal.
      </p>
    `
    );
  }

  private buildParentHtml(
    status: string,
    parentName: string,
    relationship: string,
    studentName: string,
    studentId: string,
    department: string,
    sessionName: string,
    date: string,
    time: string,
    lateBy?: number
  ): string {
    let badge = { text: "WARD PRESENT", color: "#16a34a" };
    let headline = "Attendance Recorded Successfully";
    let message = `This is to inform you that your ward, <strong>${studentName}</strong>, was present and marked attendance for the session detailed below.`;

    if (status === "late") {
      badge = { text: `WARD LATE (${lateBy || 10} MIN)`, color: "#d97706" };
      headline = "Late Arrival Alert";
      message = `This is an alert that your ward, <strong>${studentName}</strong>, arrived late to class by approximately ${lateBy || 10} minute(s).`;
    } else if (status === "absent") {
      badge = { text: "WARD ABSENT ALERT", color: "#dc2626" };
      headline = "Absence Notification";
      message = `This is an urgent notification that your ward, <strong>${studentName}</strong>, was marked <strong>ABSENT</strong> for the session detailed below.`;
    }

    const rows = [
      { label: "Student Name", value: studentName },
      { label: "Student ID", value: studentId },
      { label: "Department", value: department },
      { label: "Session Name", value: sessionName },
      { label: "Date", value: date },
      { label: "Recorded Time", value: time },
      { label: "Attendance Status", value: `<span style="color:${badge.color};font-weight:700;">${status.toUpperCase()}</span>` },
      { label: "Recipient", value: `${parentName} (${relationship})` },
    ];

    return emailShell(
      `Attendance Alert for ${studentName}`,
      badge.text,
      badge.color,
      `
      <h2 style="margin:0 0 8px;font-size:20px;font-weight:700;color:#0f172a;">${headline}</h2>
      <p style="font-size:14px;line-height:1.6;margin:0 0 16px;color:#334155;">
        Dear <strong>${parentName}</strong>,
      </p>
      <p style="font-size:14px;line-height:1.6;margin:0 0 16px;color:#334155;">
        ${message}
      </p>
      ${dataTable(rows)}
      <div style="background:#eff6ff;border-left:4px solid ${BRAND_COLOR};padding:12px 16px;border-radius:4px;margin-top:16px;">
        <p style="margin:0;font-size:13px;color:#1e40af;line-height:1.5;">
          <strong>Campus Safety Guarantee:</strong> ${BRAND_NAME} sends real-time attendance alerts to ensure student safety and transparency between the institution and parents.
        </p>
      </div>
    `
    );
  }
}

export const attendanceNotificationService = new AttendanceNotificationService();
